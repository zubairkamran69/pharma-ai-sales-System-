def token(u):
    payload = {'id':u['id'],'role':u['role'],'jti':str(uuid.uuid4()),'exp':datetime.datetime.now(datetime.timezone.utc)+datetime.timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)}
    return jwt.encode(payload,SECRET,algorithm='HS256')
def auth(authorization: str|None=Header(default=None)):
    if not authorization: raise HTTPException(401,'Authentication required')
    try:
        token_text = authorization.replace('Bearer ','').strip()
        p = jwt.decode(token_text,SECRET,algorithms=['HS256'])
    except Exception:
        raise HTTPException(401,'Invalid or expired session')
    if p.get('jti') in JWT_BLACKLIST:
        raise HTTPException(401,'Invalid or expired session')
    c=db(); u=c.execute('select * from users where id=?',(p['id'],)).fetchone(); c.close()
    if not u: raise HTTPException(401,'User not found')
    u=row(u)
    if u.get('verification_status') not in ('approved','demo') and u['role']!='admin': raise HTTPException(403,'Account is awaiting verification')
    return u
def guard(role=None):
    def dep(authorization: str|None=Header(default=None)):
        u=auth(authorization)
        if role and u['role']!=role: raise HTTPException(403,'Permission denied')
        return u
    return dep

def owner_company_id(u): return u['id'] if u['role']=='pharma' else u.get('company_user_id')

def human_conversation_allowed(u, conv):
    conv_data = dict(conv) if hasattr(conv, 'keys') else conv
    if not conv_data or conv_data.get('conversation_type') != 'human':
        return False
    if u['role'] == 'admin':
        return False
    if u['role'] == 'doctor':
        return conv_data.get('doctor_id') == u['id']
    target_company = owner_company_id(u)
    company_values = {v for v in (conv_data.get('company_id'), conv_data.get('company_user_id')) if v is not None}
    if u['role'] == 'pharma':
        return target_company is not None and target_company in company_values
    if u['role'] == 'sales_rep':
        return target_company is not None and target_company in company_values
    return False

def derive_company_code(company_name: str) -> str:
    letters = re.sub(r'[^A-Za-z]', '', (company_name or 'GEN')).upper()
    if not letters:
        return 'GEN'
    code = ''.join(ch for ch in letters if ch.isalpha())[:3]
    if len(code) < 3:
        code = (code + 'X' * 3)[:3]
    return code

def generate_sales_id(c, company_name: str) -> str:
    base = derive_company_code(company_name)
    candidate = None
    for suffix in range(100, 2000000):
        candidate = f'{base}-{suffix}'
        exists = c.execute('select 1 from users where sales_id=? or registration_number=? limit 1', (candidate, candidate)).fetchone()
        if not exists:
            return candidate
    raise HTTPException(500, 'Unable to generate a unique sales ID for this company')

