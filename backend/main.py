def generate_order_number(c):
    date_key = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d')
    for attempt in range(1, 20000):
        suffix = str(1000 + attempt + int(date_key[-2:]))
        candidate = f'ORD-{date_key}-{suffix}'
        exists = c.execute('select 1 from orders where order_no=? or order_number=? limit 1', (candidate, candidate)).fetchone()
        if not exists:
            return candidate
    raise HTTPException(500, 'Unable to generate a unique order number')


