def _store_document(c,u,medicine_id,file,doc_type):
    allowed={'.pdf','.docx','.txt','.md'}; ext=os.path.splitext(file.filename or '')[1].lower()
    if ext not in allowed: c.close(); raise HTTPException(400,'Supported files: PDF, DOCX, TXT, MD')
    content=file.file.read()
    cur=c.execute('insert into documents(medicine_id,filename,path,status,created_at,owner_user_id,document_type,file_data) values(?,?,?,?,?,?,?,?)',(medicine_id,file.filename,None,'Processing',now(),owner_company_id(u),doc_type,content)); did=cur.lastrowid; c.commit()
    try:
        result=MedicineRAG(c).ingest(medicine_id,did,None,file.filename,content=content); result.update({'ok':True,'filename':file.filename,'document_type':doc_type}); c.close(); return result
    except Exception as e:
        c.execute('update documents set status=? where id=?',('Error: '+str(e)[:180],did)); c.commit(); c.close(); raise HTTPException(400,'Document could not be indexed: '+str(e))
