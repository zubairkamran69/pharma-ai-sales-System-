def agent_answer(u, msg):
    c = db()
    risk = risk_level(msg)
    q = msg.lower().strip()

    # =========================================================
    # 1. SAFETY GATE
    # =========================================================

    if risk == 'critical':

        t = now()

        no = (
            'TKT-'
            + str(
                2000
                + c.execute(
                    'select count(*) x from tickets'
                ).fetchone()['x']
                + 1
            )
        )

        if any(
            k in q
            for k in [
                'adverse event',
                'allergic reaction',
                'side effect'
            ]
        ):
            dept = 'Pharmacovigilance'
        else:
            dept = 'Medical Affairs'

        c.execute(
            '''
            INSERT INTO tickets(
                ticket_no,
                user_id,
                subject,
                content,
                priority,
                department,
                status,
                created_at,
                updated_at
            )
            VALUES(?,?,?,?,?,?,?,?,?)
            ''',
            (
                no,
                u['id'],
                'Safety-critical medicine question',
                msg,
                'Critical',
                dept,
                'Open',
                t,
                t
            )
        )

        c.commit()
        c.close()

        return {
            'agent': 'Risk & Escalation Agent',
            'risk': 'critical',
            'message': (
                'This question needs qualified human review, '
                'so I will not guess or provide a potentially unsafe '
                'answer. I opened **'
                + no
                + '** and routed the original conversation to **'
                + dept
                + '**. A qualified reviewer can continue from '
                  'the same case context.'
            ),
            'ticket_no': no,
            'sources': [],
            'provider': 'safety-gate'
        }

    # =========================================================
    # 1b. MEDICAL TRIGGER ROUTER
    #     Any medical word / medicine name => RAG is mandatory.
    # =========================================================

    route = medical_router.classify(msg, all_medicines(c))
    medical = (
        route['medical']
        or is_product_question(q)
        or is_medicine_related(q)
    )

    # =========================================================
    # 2. GREETING  (only pure greetings - never a medical question)
    # =========================================================

    if (not medical) and re.match(
        r'^(hi|hello|hey|salam|assalam|good morning|good afternoon|good evening)\b',
        q
    ):

        c.close()

        if u['role'] == 'pharma':
            return {
                'agent': 'Supervisor Agent',
                'risk': 'low',
                'message': (
                    f"Hello {u['name']}! I'm your PharmaAI company "
                    "agent. I can answer general questions, search "
                    "approved product knowledge, help with RAG, "
                    "medicines, doctors, sales representatives, "
                    "orders, analytics and company workflows."
                ),
                'sources': [],
                'provider': 'supervisor'
            }

        if u['role'] == 'sales_rep':
            return {
                'agent': 'Supervisor Agent',
                'risk': 'low',
                'message': (
                    f"Hello {u['name']}! I'm your PharmaAI sales "
                    "workspace agent. I can help with general "
                    "questions, approved product knowledge, RAG, "
                    "doctors, sales workflows and company information."
                ),
                'sources': [],
                'provider': 'supervisor'
            }

        return {
            'agent': 'Supervisor Agent',
            'risk': 'low',
            'message': (
                f"Hello {u['name']}! I'm your PharmaAI assistant. "
                "I can answer general questions, search approved "
                "medicine documents, help with medicines and connect "
                "you with company representatives."
            ),
            'sources': [],
            'provider': 'supervisor'
        }

    # =========================================================
    # 3. DOCUMENT / KNOWLEDGE ONBOARDING
    # =========================================================

    if (
        u['role'] in ('pharma', 'sales_rep')
        and is_onboarding_request(q)
    ):

        c.close()

        return {
            'agent': 'Knowledge Onboarding Agent',
            'risk': 'low',
            'message': (
                'Upload an approved PDF, DOCX, TXT or Markdown '
                'document from **Knowledge Center**. For a new '
                'medicine, create the medicine first, select it '
                'in Knowledge Center, upload its approved product '
                'document and index it. The system extracts text, '
                'creates chunks and makes the information available '
                'to RAG search.'
            ),
            'sources': [],
            'provider': 'supervisor'
        }

    # =========================================================
    # 4. DOCTOR DIRECTORY
    # =========================================================

    if (
        u['role'] in ('pharma', 'sales_rep')
        and is_doctor_directory_request(q)
    ):

        ds = rows(
            c.execute(
                '''
                SELECT
                    name,
                    email,
                    specialization,
                    created_at,
                    verification_status
                FROM users
                WHERE role='doctor'
                ORDER BY created_at DESC
                '''
            ).fetchall()
        )

        c.close()

        lines = [
            f"• {d['name']} — "
            f"{d['specialization']} — "
            f"{d['email']} — "
            f"{d['verification_status']}"
            for d in ds[:100]
        ]

        return {
            'agent': 'Doctor Intelligence Agent',
            'risk': 'low',
            'message': (
                f'I found **{len(ds)} registered doctors** '
                'in the platform.\n\n'
                + '\n'.join(lines)
            ),
            'sources': [],
            'provider': 'structured-directory'
        }

    # =========================================================
    # 5. SALES REPRESENTATIVE DIRECTORY
    # =========================================================

    if (
        u['role'] in ('pharma', 'sales_rep')
        and is_rep_directory_request(q)
    ):

        oid = owner_company_id(u)

        reps = rows(
            c.execute(
                '''
                SELECT
                    name,
                    email,
                    phone,
                    job_title,
                    registration_number
                FROM users
                WHERE
                    role='sales_rep'
                    AND company_user_id=?
                ''',
                (oid,)
            ).fetchall()
        )

        c.close()

        lines = [
            f"• {r['name']} — "
            f"{r['job_title']} — "
            f"{r['email']} — "
            f"{r['phone'] or 'no phone'}"
            for r in reps
        ]

        return {
            'agent': 'Sales Workforce Agent',
            'risk': 'low',
            'message': (
                f'Your company has **{len(reps)} sales '
                'representatives** registered.\n\n'
                + '\n'.join(lines)
            ),
            'sources': [],
            'provider': 'structured-directory'
        }

    # =========================================================
    # 6. STRUCTURED COMMERCIAL DATA
    # =========================================================

    if (
        u['role'] in ('pharma', 'sales_rep')
        and is_commercial_request(q)
    ):

        medicines = c.execute(
            'select * from medicines order by id desc'
        ).fetchall()

        lines = [
            f"• **{m['name']}** "
            f"({m['company']}) — "
            f"price ${m['price']:.2f}; "
            f"stock {m['stock']} units."
            for m in medicines[:10]
        ]

        c.close()

        return {
            'agent': 'Sales + Commercial Tool Agent',
            'risk': 'low',
            'message': (
                'Here is the current structured commercial '
                'information:\n\n'
                + '\n'.join(lines)
                + '\n\nThese values come from the system database, '
                  'not model memory.'
            ),
            'sources': [],
            'provider': 'structured-tool'
        }

    # =========================================================
    # 7. MEDICAL MESSAGE  ->  RAG ONLY (never general knowledge)
    # =========================================================

    if system_help_request(msg):
        role_answer = system_help_role_answer(u, msg)
        c.close()
        return {
            'agent': 'System Help / Product Knowledge Agent',
            'risk': 'low',
            'message': role_answer,
            'sources': [],
            'provider': 'system-help-kb',
            'route': 'system_help',
            'triggers': []
        }

    if medical:

        context = rag_context(c, u, msg, route['medicines'])
        c.close()

        named = ', '.join(m['name'] for m in route['medicines'])

        # 7a. No approved evidence -> do NOT call the LLM at all.
        if not context:
            fallback = general_medicine_fallback_response(msg, [m['name'] for m in route['medicines']] if route.get('medicines') else [])
            return {
                'agent': 'Product Knowledge + RAG Agent',
                'risk': risk,
                'message': fallback,
                'sources': [],
                'provider': 'general-medicine-fallback',
                'route': 'general-medicine-fallback',
                'triggers': route['triggers']
            }

        # 7b. Evidence found -> LLM may only rephrase what the sources say.
        result = LLMClient().generate(
            MEDICAL_RAG_SYSTEM,
            msg,
            context,
            strict=True
        )

        sources = [
            {
                'source_no': i + 1,
                'filename': x['filename'],
                'chunk': x['chunk_no'],
                'score': x['score'],
                'medicine': x.get('medicine_name', ''),
                'preview': x['content'][:220]
            }
            for i, x in enumerate(context)
        ]

        verified_text = result.get('text', '').strip()
        if verified_text and 'pharmaai verified information' not in verified_text.lower():
            verified_text = 'PharmaAI Verified Information\n\n' + verified_text

        return {
            'agent': 'Product Knowledge + RAG Agent',
            'risk': risk,
            'message': verified_text,
            'sources': sources,
            'provider': result.get('provider', 'groq:openai/gpt-oss-20b'),
            'route': 'rag',
            'triggers': route['triggers']
        }

    # =========================================================
    # 8. NON-MEDICAL MESSAGE -> general assistant (no RAG)
    # =========================================================

    c.close()

    result = LLMClient().generate(
        GENERAL_SYSTEM,
        msg,
        []
    )

    return {
        'agent': 'Supervisor + General Knowledge Agent',
        'risk': risk,
        'message': result['text'],
        'sources': [],
        'provider': result.get('provider', 'groq:openai/gpt-oss-20b'),
        'route': 'general',
        'triggers': []
    }


