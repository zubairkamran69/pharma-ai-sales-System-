def _normalize_sql_for_postgres(sql):
    return sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')

class PostgresCompatCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def __getattr__(self, name):
        return getattr(self._cursor, name)

class PostgresCompatConnection:
    def __init__(self, conn):
        self.conn = conn

    def execute(self, sql, params=None):
        sql = _normalize_sql_for_postgres(sql)
        pragma = re.fullmatch(r'\s*pragma\s+table_info\((\w+)\)\s*', sql, flags=re.IGNORECASE)
        if pragma:
            sql = 'SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position'
            params = (pragma.group(1).lower(),)
        sql = re.sub(r'\?', '%s', sql)
        is_insert = re.match(r'^\s*insert\b', sql, flags=re.IGNORECASE) is not None
        if is_insert and 'returning' not in sql.lower():
            sql = f'{sql.rstrip().rstrip(";")} RETURNING id'
        cursor = self.conn.cursor(cursor_factory=psycopg2_extras.DictCursor)
        if isinstance(params, dict):
            params = tuple(params.values())
        elif isinstance(params, list):
            params = tuple(params)
        if params is None:
            cursor.execute(sql)
        else:
            cursor.execute(sql, params)
        lastrowid = None
        if is_insert:
            inserted = cursor.fetchone()
            lastrowid = inserted[0] if inserted else None
        return PostgresCompatCursor(cursor, lastrowid)

    def executescript(self, sql_script):
        for statement in [chunk.strip() for chunk in sql_script.split(';') if chunk.strip()]:
            self.execute(statement)

    def commit(self):
        self.conn.commit()

    def close(self):
        self.conn.close()


