def phash(value):
    rounds = 310000
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac('sha256', value.encode(), salt, rounds)
    return f'pbkdf2_sha256${rounds}${salt.hex()}${digest.hex()}'


def pverify(value, hashed):
    if hashed.startswith('pbkdf2_sha256$'):
        try:
            algorithm, rounds, salt_hex, digest_hex = hashed.split('$', 3)
            if algorithm != 'pbkdf2_sha256':
                return False
            digest = hashlib.pbkdf2_hmac('sha256', value.encode(), bytes.fromhex(salt_hex), int(rounds))
            return secrets.compare_digest(digest.hex(), digest_hex)
        except (ValueError, TypeError):
            return False
    legacy_hash = hashlib.sha256(('pharmaai:' + value).encode()).hexdigest()
    return secrets.compare_digest(legacy_hash, hashed)


