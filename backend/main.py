def validate_order_transition(current_status, next_status):
    current = (current_status or 'Pending').strip()
    next_value = (next_status or 'Pending').strip()
    if next_value not in ORDER_STATUSES:
        return False
    if current == next_value:
        return True
    if next_value in ORDER_STATUS_TRANSITIONS.get(current, set()):
        return True
    return False


