CRITICAL=['patient-specific','patient specific','patient','pregnan','renal','kidney failure','overdose','adverse event','allergic reaction','dose change','dosage change','prescribe','emergency','severe side effect','contraindication']
def risk_level(msg):
    q=msg.lower()
    if any(k in q for k in CRITICAL): return 'critical'
    if any(k in q for k in ['side effect','interaction','warning','precaution','safety']): return 'review'
    return 'low'
MIN_RAG_SCORE=0.05   # chunks scoring below this are treated as "no evidence"
REL_RAG_SCORE=0.30   # ...and so are chunks far weaker than the best one

def all_medicines(c): return rows(c.execute('select * from medicines').fetchall())

def resolve_medicine(c,msg):
    """First medicine named in the message (full name or brand root), or None."""
    found=medical_router.find_medicines(msg,all_medicines(c))
    return found[0] if found else None

def rag_context(c, u, msg, meds=None):
    """
    Mandatory RAG retrieval for medical / medicine messages.

    - exactly one medicine named  -> search only that medicine's documents
    - none / several named        -> search the whole accessible knowledge base
    - pharma / sales_rep          -> only their own company's documents
    - doctor                      -> approved documents of all companies
    """
    meds = meds or []
    medicine_id = meds[0]['id'] if len(meds) == 1 else None
    owner = owner_company_id(u) if u['role'] in ('pharma','sales_rep') else None
    hits = MedicineRAG(c).retrieve(
        medical_router.retrieval_query(msg),
        medicine_id=medicine_id,
        top_k=8,
        owner_user_id=owner
    )
    if len(meds) > 1:                       # keep only the medicines asked about
        ids = {m['id'] for m in meds}
        hits = [h for h in hits if h.get('medicine_id') in ids or not h.get('medicine_id')]
    top = max((h['score'] for h in hits), default=0)
    hits = [h for h in hits if h['score'] >= max(MIN_RAG_SCORE, REL_RAG_SCORE * top)]
    if hits and not meds:
        text = ' '.join((h['content'] + ' ' + (h.get('medicine_name') or '')) for h in hits)
        if medical_router.unknown_drug_terms(msg, text):
            return []                       # asked about a drug the KB does not have
    return hits

