def serialize_specializations(value):
    if value is None:
        return json.dumps([])
    if isinstance(value, str):
        text = value.strip()
        if not text:
            return json.dumps([])
        try:
            parsed = json.loads(text)
        except json.JSONDecodeError:
            parsed = [text]
        if not isinstance(parsed, list):
            parsed = [parsed]
    elif isinstance(value, (list, tuple, set)):
        parsed = list(value)
    else:
        parsed = [value]
    normalized = [str(item).strip() for item in parsed if str(item).strip()]
    return json.dumps(normalized)


def normalize_medicine_fields(payload: dict, *, require_company: bool = False) -> dict:
    data = dict(payload)
    name = str(data.get('name') or '').strip()
    category = str(data.get('category') or '').strip()
    manufacturer = str(data.get('manufacturer') or '').strip() or str(data.get('company') or '').strip()
    if not name:
        raise HTTPException(400, 'Medicine name is required')
    if not category:
        raise HTTPException(400, 'Category is required')
    if require_company and not manufacturer:
        raise HTTPException(400, 'Manufacturer / pharma company is required')
    if 'price' in data:
        try:
            price = float(data['price'])
        except (TypeError, ValueError):
            raise HTTPException(400, 'Price must be a valid numeric value')
        if not math.isfinite(price) or price < 0:
            raise HTTPException(400, 'Price cannot be negative and must be numeric')
        data['price'] = round(price, 2)
    data['currency'] = 'PKR'
    data['manufacturer'] = manufacturer
    for key in ['generic_name', 'brand_name', 'therapeutic_area', 'dosage_form', 'strength', 'pack_size', 'availability_status', 'status', 'prescription_status', 'description', 'composition', 'indications', 'contraindications', 'warnings', 'storage_information']:
        if key in data and data[key] is not None:
            data[key] = str(data[key]).strip()
    if 'specializations' in data and data['specializations'] is not None:
        data['specializations'] = serialize_specializations(data['specializations'])
    else:
        data['specializations'] = serialize_specializations([])
    if 'stock' in data and data['stock'] is not None:
        try:
            data['stock'] = int(data['stock'])
        except (TypeError, ValueError):
            raise HTTPException(400, 'Stock quantity must be a valid number')
        if data['stock'] < 0:
            raise HTTPException(400, 'Stock quantity cannot be negative')
    return data


