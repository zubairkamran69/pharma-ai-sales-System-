def normalize_order_status(value):
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    lookup = {
        'pending': 'Pending',
        'under review': 'Under Review',
        'under_review': 'Under Review',
        'underreview': 'Under Review',
        'assigned': 'Assigned',
        'confirmed': 'Confirmed',
        'processing': 'Processing',
        'dispatched': 'Dispatched',
        'delivered': 'Delivered',
        'rejected': 'Rejected',
        'cancelled': 'Cancelled',
        'canceled': 'Cancelled',
    }
    key = text.lower().replace('-', ' ').replace('_', ' ')
    key = ' '.join(key.split())
    if key in lookup:
        return lookup[key]
    return None

